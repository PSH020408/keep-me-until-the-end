#!/usr/bin/env python3
"""Turn the painted art (GPT sheets and single pictures in art_raw/) into the WebP files the game loads.

  python3 tools/import_assets.py [SRC] [--only fish,bg,...]

SRC defaults to art_raw/. Output goes to public/img/ and the fish rig to public/js/data/rig.js.
Fish parts are cut from parts.png (body, tail, dorsal, pectoral, pelvic+anal, closed-eye head),
rigged automatically (tail matched to the body's rear socket, fins scaled to the body's height) and
saved as separate layers so the browser can swing the tail and flutter the fins.
Per-species corrections live in tools/rig_overrides.json."""
import sys,os,json,glob
from PIL import Image
sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
from cells import cut_cells
from rig import rig,compose,plug_head
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args=[a for a in sys.argv[1:] if not a.startswith('--')]
SRC=os.path.join(ROOT,args[0] if args else 'art_raw')
ONLY=next((a.split('=')[1].split(',') for a in sys.argv if a.startswith('--only=')),None)
OUT=os.path.join(ROOT,'public','img')
def want(k): return ONLY is None or k in ONLY
SPONLY=next((a.split('=')[1].split(',') for a in sys.argv if a.startswith('--sp=')),None)
CACHE=os.path.join(ROOT,'tools','.rig_cache')
FORCE='--force' in sys.argv
def save(im,path,q=80,maxw=None,maxh=None,trim=False):
    os.makedirs(os.path.dirname(path),exist_ok=True)
    if not FORCE and os.path.exists(path) and ONLY and 'fish' not in ONLY: return None
    if trim and im.mode=='RGBA':
        bb=im.getchannel('A').point(lambda v:255 if v>8 else 0).getbbox()
        if bb: im=im.crop(bb)
    if maxw and im.width>maxw: im=im.resize((maxw,round(im.height*maxw/im.width)),Image.LANCZOS)
    if maxh and im.height>maxh: im=im.resize((round(im.width*maxh/im.height),maxh),Image.LANCZOS)
    im.save(path,'WEBP',quality=q,method=4)
    return im.size
def src(*p): return os.path.join(SRC,*p)
log=[]
SPECIES='guppy betta neon oranda koi cory comet ryukin platy oscar pleco arowana clownloach apisto wildbetta altum channa peapuffer fig8 bichir ghost motoro gar'.split()
POSES='front three flop jump mouth proud charge dizzy deadside thin bent frozen'.split()
# ---- fish ----
if want('fish'):
    OV=json.load(open(os.path.join(ROOT,'tools','rig_overrides.json')))
    RIG={}
    os.makedirs(CACHE,exist_ok=True)
    for sp in SPECIES:
        if SPONLY and sp not in SPONLY: continue
        ov=OV.get(sp,{})
        parts=cut_cells(Image.open(src('01_fish',sp,'parts.png')),3,2)
        if ov.get('plug'): parts=plug_head(parts,ov)
        P=rig(parts,ov)
        names=('body','tail','dorsal','pect','pelvic','head')
        comp,(ox,oy)=compose(parts,P)
        k=min(1,560/comp.width)                    # export scale: whole fish at most 560px long
        layers={}
        for nm,im in zip(names,parts):
            p=P[nm]; s=p['s']*k
            w,h=max(1,round(im.width*s)),max(1,round(im.height*s))
            save(im.resize((w,h),Image.LANCZOS),os.path.join(OUT,'fish',sp,nm+'.webp'),q=82)
            layers[nm]=dict(x=round((p['x']+ox)*k,1),y=round((p['y']+oy)*k,1),w=w,h=h,
                px=round(p.get('px',0)*s,1),py=round(p.get('py',0)*s,1))
        W,H=round(comp.width*k),round(comp.height*k)
        save(comp,os.path.join(OUT,'fish',sp,'swim.webp'),q=82,maxw=360)
        RIG[sp]=dict(w=W,h=H,l=layers); json.dump(RIG[sp],open(os.path.join(CACHE,sp+'.json'),'w'))
        poses=cut_cells(Image.open(src('01_fish',sp,'poses.png')),4,3)
        for nm,im in zip(POSES,poses):
            if im is not None: save(im,os.path.join(OUT,'fish',sp,'p-'+nm+'.webp'),q=80,maxw=420,maxh=420)
        log.append(f'fish {sp}: {W}x{H}')
    RIG={sp:json.load(open(os.path.join(CACHE,sp+'.json'))) for sp in SPECIES if os.path.exists(os.path.join(CACHE,sp+'.json'))}
    with open(os.path.join(ROOT,'public','js','data','rig.js'),'w') as f:
        f.write('/* fish rig: layer boxes in px of the assembled fish (generated by tools/import_assets.py; do not edit) */\n')
        f.write('const RIG='+json.dumps(RIG,separators=(',',':'))+';\n')
# ---- full-frame paintings: places, endings, glory, career, gags, the four mob scenes ----
SCENES={'02_bg':'bg','07_ending':'end','08_glory':'glory','09_career':'career','13_gag':'gag'}
PART=next((a.split('=')[1] for a in sys.argv if a.startswith('--dir=')),None)
if want('bg'):
    for d,o in SCENES.items():
        if PART and d!=PART: continue
        for f in sorted(glob.glob(src(d,'*.png'))):
            n=os.path.basename(f)[:-4]
            if n=='title-frame': continue
            save(Image.open(f).convert('RGB'),os.path.join(OUT,o,n+'.webp'),q=72,maxw=1280)
    for n in (['suseon-form','suseon-march','yankee-form','yankee-ride'] if not PART or PART=='12_mob' else []):
        save(Image.open(src('12_mob',n+'.png')).convert('RGB'),os.path.join(OUT,'mob',n+'.webp'),q=72,maxw=1280)
    log.append('scenes done')
# ---- cut-outs ----
if want('cut'):
    for f in glob.glob(src('03_owner','*.png')): save(Image.open(f),os.path.join(OUT,'owner',os.path.basename(f)[:-4]+'.webp'),q=80,maxh=720,trim=True)
    for d,o,m in [('04_animal','animal',560),('05_hand','hand',560),('06_prop','prop',360)]:
        for f in glob.glob(src(d,'*.png')): save(Image.open(f),os.path.join(OUT,o,os.path.basename(f)[:-4]+'.webp'),q=82,maxw=m,maxh=m,trim=True)
    for f in glob.glob(src('12_mob','*.png')):
        n=os.path.basename(f)[:-4]
        if n in ('suseon-form','suseon-march','yankee-form','yankee-ride'): continue
        save(Image.open(f),os.path.join(OUT,'mob',n+'.webp'),q=82,maxw=420,maxh=420,trim=True)
    for f in glob.glob(src('14_ui','*.png')): save(Image.open(f),os.path.join(OUT,'ui',os.path.basename(f)[:-4]+'.webp'),q=84,maxw=1280)
    save(Image.open(src('08_glory','title-frame.png')),os.path.join(OUT,'ui','title-frame.webp'),q=84,maxw=1280)
    log.append('cut-outs done')
# ---- icon and overlay sheets ----
if want('icons'):
    icons=cut_cells(Image.open(src('10_skill','skills-1.png')),4,3)+cut_cells(Image.open(src('10_skill','skills-2.png')),4,3,count=7)
    for i,im in enumerate([x for x in icons if x is not None][:19]): save(im,os.path.join(OUT,'skill',f'{i+1:02d}.webp'),q=82,maxw=160,trim=True)
    for i,im in enumerate(cut_cells(Image.open(src('11_sick','sick.png')),4,3)):
        if im is not None: save(im,os.path.join(OUT,'sick',f'{i+1:02d}.webp'),q=80,maxw=320,trim=True)
    log.append('icons done')
print('\n'.join(log))
